const originals = new WeakMap();
const originalAttributes = new WeakMap();
let preference = localStorage.getItem("voicehub-studio-language") || "system";
let locale = resolvePreference(preference);

function resolvePreference(value) {
  if (value === "tr" || value === "en") return value;
  return String(navigator.language || "en").toLowerCase().startsWith("tr") ? "tr" : "en";
}

export function getLocale() {
  return locale;
}

export function getLocalePreference() {
  return preference;
}

export function t(value) {
  const text = String(value ?? "");
  if (locale !== "tr" || !text) return text;
  if (Object.hasOwn(TURKISH, text)) return TURKISH[text];
  for (const [pattern, replacement] of TURKISH_PATTERNS) {
    if (pattern.test(text)) return text.replace(pattern, replacement);
  }
  return text;
}

function shouldSkipText(node) {
  const parent = node.parentElement;
  if (!parent) return true;
  return Boolean(parent.closest("script, style, textarea, pre, code, .mono, [data-i18n-skip]"));
}

function translateTextNode(node) {
  if (shouldSkipText(node)) return;
  const source = originals.get(node) ?? node.nodeValue;
  if (!originals.has(node)) originals.set(node, source);
  const match = String(source).match(/^(\s*)([\s\S]*?)(\s*)$/);
  if (!match || !match[2]) return;
  node.nodeValue = `${match[1]}${locale === "tr" ? t(match[2]) : match[2]}${match[3]}`;
}

function translateAttributes(element) {
  const names = ["placeholder", "title", "aria-label"];
  let saved = originalAttributes.get(element);
  if (!saved) {
    saved = {};
    originalAttributes.set(element, saved);
  }
  for (const name of names) {
    if (!element.hasAttribute(name)) continue;
    if (!(name in saved)) saved[name] = element.getAttribute(name);
    element.setAttribute(name, locale === "tr" ? t(saved[name]) : saved[name]);
  }
}

export function localizeTree(root = document) {
  document.documentElement.lang = locale;
  const elementRoot = root.nodeType === Node.ELEMENT_NODE ? root : document.documentElement;
  translateAttributes(elementRoot);
  elementRoot.querySelectorAll?.("*").forEach(translateAttributes);
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) translateTextNode(walker.currentNode);
}

export function setLocalePreference(value, { translate = true } = {}) {
  preference = ["system", "en", "tr"].includes(value) ? value : "system";
  locale = resolvePreference(preference);
  localStorage.setItem("voicehub-studio-language", preference);
  document.documentElement.lang = locale;
  if (translate) localizeTree(document);
  return locale;
}

